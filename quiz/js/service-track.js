/** מחזיר את חבילת התצוגה, או null כשאין קוד P (מסלולי עסק/בניין, deep-link). */
export function serviceTrack(pCode) {
  const kind = SERVICE_FROM_PCODE[pCode];
  if (!kind) return null;
  return {
    kind,
    label: SERVICE_LABEL[kind],
    lines: EXPLANATION[kind],
    steps: STEPS[kind],
    outro: OUTRO[kind],
  };
}
