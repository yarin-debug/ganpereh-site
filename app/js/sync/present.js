/* מה המסך אומר — הגזירות הטהורות של מסך הסנכרון.

   בלי DOM, בלי רשת, בלי גישה ל-store. הכל כאן הוא קלט → מחרוזת, ולכן
   נבדק ישירות ב-dev/tests.js.

   ההפרדה הזו אינה סדר וניקיון. רוב המסך הזה *הוא* טקסט מצב — "סונכרן
   לפני רגע" מול "אין כרגע חיבור" מול "ההתחברות פגה" — והטקסט הוא בדיוק
   מה שנשבר כשמצב חדש נוסף למנוע ואיש לא בדק מה המסך אומר עליו.

   auth.js ו-rest.js מייבאים מכאן את הנרמולים במקום להחזיק עותק. הממשק
   חייב לפסול קלט פגום *לפני* שהוא שולח בקשה, והבדיקה בשליחה חייבת
   להישאר בכל מקרה — ושני עותקים של אותו כלל נפרדים זה מזה בסיבוב הבא. */

/* ---------- כתובת מייל ---------- */

/**
 * מנרמל ומאמת כתובת מייל.
 *
 * הכלל נשאר "יש בה שטרודל", ובכוונה. ביטוי רגולרי הדוק יותר היה פוסל
 * כתובות תקינות (תווית עברית, סיומת חדשה, פלוס בתווית) — וכישלון
 * בכיוון הזה גרוע בהרבה מהחלופה: כתובת שגויה פשוט לא תקבל מייל,
 * והמשתמש רואה את זה מיד. כתובת תקינה שנפסלת חוסמת את הכניסה לגמרי,
 * ולמשתמש אין שום דרך לעקוף אותה.
 *
 * @returns {{ok: boolean, email: string, error: string|null}}
 */
export function normalizeEmail(raw) {
  const email = String(raw || "")
    .trim()
    .toLowerCase();
  if (!email) return { ok: false, email, error: "צריך להזין כתובת מייל." };
  if (!email.includes("@")) return { ok: false, email, error: "כתובת המייל אינה תקינה." };
  return { ok: true, email, error: null };
}

/* ---------- קוד ההזמנה ---------- */

/**
 * מנקה קוד שהוקלד ביד.
 *
 * מוסרים רווחים ומקפים — הקוד מוצג מקובץ ("ABCD EFGH"), ומי שמעתיק
 * אותו כמו שהוא מעתיק גם את הרווח. אותיות קטנות עולות לגדולות.
 *
 * ── מה במכוון *לא* קורה כאן ─────────────────────────────────────────
 * הפיתוי הוא למפות תווים מתבלבלים: O←0, I←1, L←1. באלפבית שממנו
 * נגזר הקוד (rest.js) **שני** התווים של כל זוג חסרים — אין בו לא O
 * ולא 0, לא I ולא 1 ולא L. כלומר מי שהקליד אחד מהם שמע משהו לא נכון,
 * ואין תו יחיד שאפשר לתקן אליו. מיפוי כזה היה ניחוש, וניחוש שמצליח
 * חצי מהפעמים גרוע מקוד שנדחה מיד עם "הקוד אינו תקף".
 */
export function normalizeInviteCode(raw) {
  return String(raw || "")
    .replace(/[\s –—.\-_]/g, "")
    .toUpperCase();
}

/**
 * מקבץ את הקוד לקריאה בקול.
 *
 * הקוד נאמר בטלפון, לא מודבק. שמונה תווים ברצף נקראים כמחרוזת אחת
 * ומאבדים את המקום באמצע; שתי רביעיות הן שתי "מילים" שאפשר לחזור על
 * כל אחת מהן בנפרד. אותו נימוק בדיוק שבגללו האלפבית מוותר על O ועל 1.
 */
export function formatInviteCode(code) {
  const clean = normalizeInviteCode(code);
  return clean.replace(/(.{4})(?=.)/g, "$1 ");
}

/* ---------- כשל שליחה ---------- */

/**
 * למה הקישור לא נשלח, בעברית.
 *
 * ── למה לא להעביר את הודעת השרת ─────────────────────────────────────
 * הודעות Supabase אנגליות ("Email rate limit exceeded"), וכל מחרוזת
 * שהמשתמש רואה באפליקציה הזו היא בעברית. `authFetch` שומר את הנוסח
 * המקורי ב-`detail` כדי שמי שמנפה תקלה ימצא אותו, ואינו מציג אותו.
 *
 * מה שנשאר הוא הסטטוס, ורק אחד ממנו באמת דורש משפט אחר: **429**.
 * "נסה שוב" הוא עצה שגויה שם — ניסיון חוזר מיד אחרי חסימת קצב רק
 * מאריך את החסימה, וזו בדיוק ההודעה שמייצרת את הלחיצה החוזרת.
 *
 * שגיאה בלי `status` הגיעה מהפסילה המקומית (`normalizeEmail`), ולכן
 * ההודעה שלה כבר בעברית ומדויקת יותר מכל ניסוח כללי.
 */
export function sendFailure(error) {
  if (error?.status === 429) {
    return "נשלחו יותר מדי בקשות בזמן קצר. אפשר לנסות שוב בעוד דקה.";
  }
  if (error?.status === undefined && error?.message) return error.message;
  return "לא הצלחנו לשלוח את הקישור. בדוק את החיבור ונסה שוב.";
}

/* ---------- זמן ---------- */

const MINUTE = 60_000;
const HOUR = 60 * MINUTE;
const DAY = 24 * HOUR;

/**
 * "לפני כמה זמן" בעברית, כולל צורת הזוגי.
 *
 * "לפני 2 דקות" הוא בדיוק סוג המשפט שנקרא כמו תרגום מכונה. עברית
 * מבחינה בזוגי, והמחיר של ההבחנה הוא שתי שורות.
 *
 * מעבר ליממה מוותרים על המספר: הסנכרון רץ בכל חזרה למסך, ולכן פער כזה
 * אומר "לא רץ מזמן" ולא "רץ לפני שלושה ימים בדיוק". מספר מדויק שם היה
 * מדייק דבר שאין בו שום מידע.
 */
export function relativeTime(then, now) {
  const gap = Math.max(0, Number(now) - Number(then));
  if (!Number.isFinite(gap)) return "";
  if (gap < MINUTE) return "לפני רגע";
  if (gap < HOUR) {
    const minutes = Math.floor(gap / MINUTE);
    if (minutes === 1) return "לפני דקה";
    if (minutes === 2) return "לפני שתי דקות";
    return `לפני ${minutes} דקות`;
  }
  if (gap < DAY) {
    const hours = Math.floor(gap / HOUR);
    if (hours === 1) return "לפני שעה";
    if (hours === 2) return "לפני שעתיים";
    return `לפני ${hours} שעות`;
  }
  return "לפני יותר מיממה";
}

/* ---------- שורת המצב ---------- */

/**
 * המשפט שמתחת לכותרת, והגוון שלו.
 *
 * ── שלושה גוונים, והצהוב שמור ───────────────────────────────────────
 * `soft` הוא ברירת המחדל, `good` הוא קובלט ("הושלם" — אותה משמעות
 * שיש לו בכל האפליקציה), ו-`attn` הוא הצהוב.
 *
 * **חוסר חיבור אינו צהוב.** זו לא הקלה אלא ההגדרה: האפליקציה נבנתה
 * מסביב לעבודה בלי קליטה, רשימת הקניות נפתחת בסופר, וסנכרון שלא רץ
 * כרגע הוא מצב רגיל לגמרי — הנתונים שלמים במכשיר והם ייסנכרנו אחר כך.
 * לצבוע אותו כתקלה היה שוחק בדיוק את האזהרה שכן צריכה להיקרא.
 *
 * מה שכן צהוב הוא מה שנעצר ולא יזוז לבד: אסימון שפג (צריך להתחבר
 * שוב) וגרסה חדשה יותר בצד השני (צריך לרענן). בשניהם הסנכרון מפסיק
 * לעבוד עד שמישהו יעשה משהו, וזה בדיוק ההבדל.
 *
 * @param {{signedIn: boolean, status: {state: string, message: string|null, at: number|null}, now: number}} input
 * @returns {{text: string, tone: "soft"|"good"|"attn"}}
 */
export function syncLine({ signedIn, status, now }) {
  if (!signedIn) {
    return {
      text: "הנתונים יושבים במכשיר הזה בלבד.",
      tone: "soft",
    };
  }

  const state = status?.state || "idle";

  if (state === "syncing") return { text: "מסנכרן…", tone: "soft" };

  if (state === "ok") {
    const when = status?.at ? relativeTime(status.at, now) : "";
    return { text: when ? `סונכרן ${when}.` : "מסונכרן.", tone: "good" };
  }

  if (state === "offline") {
    return {
      text: "אין כרגע חיבור. הנתונים נשמרים במכשיר וייסנכרנו כשהוא יחזור.",
      tone: "soft",
    };
  }

  if (state === "signed_out") {
    return { text: "ההתחברות פגה. צריך להתחבר שוב כדי לחדש את הסנכרון.", tone: "attn" };
  }

  if (state === "locked") {
    // ההודעה מגיעה מהמנוע ולא נכתבת כאן שוב: היא מסבירה בדיוק איזו
    // גרסה חסמה ומה לעשות, ועותק שני שלה היה נפרד ממנה בסיבוב הבא.
    return { text: status?.message || "הסנכרון מושהה.", tone: "attn" };
  }

  // מחוברים, טרם רץ סבב. קורה בשנייה שאחרי ההתחברות ובכל טעינה עד
  // שהסבב הראשון חוזר.
  return { text: "מחוברים. הסנכרון הראשון עוד רגע.", tone: "soft" };
}

/* ---------- אריחי משק הבית ---------- */

/**
 * משק הבית כאריחים, בשפת הצורות של פס השבוע.
 *
 * ── למה אריחים ולא "1 מתוך 2" ───────────────────────────────────────
 * זו אותה שפה בדיוק שהמשתמש כבר קורא בפס השבוע ובריבועי מסך הפתיחה:
 * מקווקו = מקום שעוד ריק, אריח רך עם וי = נסגר. המקווקו כאן *הוא*
 * ההזמנה — הוא אומר "יש כאן מקום פנוי" בלי משפט שיווקי שאומר את זה
 * במילים.
 *
 * ── האריחים והכיתוב אומרים אותו דבר, ולכן רק אחד מהם מוקרא ──────────
 * מוחזרים גם צורות וגם משפט, בדיוק כמו ריבועי מסך הפתיחה מול "שלב 2
 * מתוך 3" שמתחתיהם. שם האריחים הם `aria-hidden` והמשפט נושא את
 * המידע, וכאן זה אותו הסכם: קורא מסך שהיה מקריא את שניהם היה חוזר
 * על עצמו.
 *
 * ── ולמה null אינו עצלות ────────────────────────────────────────────
 * מספר החברים מגיע מהרשת, וברירת המחדל של האפליקציה הזו היא שהרשת
 * אינה זמינה. אריח שנצייר לפי ניחוש היה עונה "רק את/ה" למי שבדיוק
 * צירף בן זוג, או להפך. כשאין תשובה לא מציירים כלום — שורת המצב לבדה
 * אומרת מספיק.
 *
 * @param {number|null} members מספר החשבונות במשק הבית, או null כשלא ידוע
 * @returns {{states: string[], caption: string}|null}
 */
export function householdTiles(members) {
  const count = Number(members);
  if (!Number.isFinite(count) || count < 1) return null;

  if (count === 1) {
    return {
      states: ["cooked", "empty"],
      caption: "רק החשבון שלך. יש מקום לעוד אחד.",
    };
  }

  return {
    states: Array(count).fill("cooked"),
    caption: count === 2 ? "שני חשבונות מסונכרנים." : `${count} חשבונות מסונכרנים.`,
  };
}
