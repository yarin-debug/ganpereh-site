/* חיבור ל-Supabase.

   ── למה המפתח הזה יושב בקוד גלוי ────────────────────────────────────
   `ANON_KEY` הוא מפתח ציבורי בכוונת המעצב. הוא אינו מקנה שום גישה
   לנתונים בעצמו — מה שמגן על השורות הוא RLS בצד השרת (`app/supabase/
   meals.sql`), שמתנה כל קריאה וכתיבה בכך שהמייל שב-JWT רשום כחבר
   באותו משק בית. בלי התחברות, המפתח פותח בדיוק כלום.

   המפתח ה*סודי* (`service_role`) לעולם לא מגיע לכאן. הוא לא נחוץ
   לאפליקציה הזו כלל.

   ── להפעלה ──────────────────────────────────────────────────────────
   שלבי ההקמה המלאים ב-`app/supabase/README.md`. בקצרה: למלא את שני
   השדות מ-Supabase → Settings → API, ולהריץ את קובץ ה-SQL.

   כל עוד השדות ריקים האפליקציה עובדת בדיוק כמו קודם — מקומית בלבד,
   בלי מסך התחברות. זו ברירת המחדל המכוונת: תצורה חסרה לא שוברת
   אפליקציה שעבדה. */

export const SUPABASE = {
  URL: "",
  ANON_KEY: "",
};

/** האם הסנכרון מוגדר בכלל. כשלא — האפליקציה נשארת מקומית ושקטה. */
export function syncConfigured() {
  return !!(SUPABASE.URL && SUPABASE.ANON_KEY);
}

/* כתובת החזרה מגוגל. נגזרת מהדף עצמו ולא נכתבת ידנית, כדי שאותו קוד
   יעבוד גם בפיתוח (127.0.0.1) וגם בייצור בלי עריכה — ושתי הכתובות
   נרשמות ב-Supabase → Authentication → URL Configuration. */
export function redirectUrl() {
  return location.origin + location.pathname.replace(/index\.html$/, "");
}

